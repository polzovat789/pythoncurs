def is_palindrome(s):
    # Приводим строку к нижнему регистру и убираем пробелы
    s = str(s).lower().replace(" ", "")
    # Сравниваем строку с её обратной версией
    return s == s[::-1]

# Получаем ввод от пользователя
user_input = input("Введите строку или число: ")

# Проверяем, является ли ввод палиндромом
if is_palindrome(user_input):
    print(f"'{user_input}' является палиндромом.")
else:
    print(f"'{user_input}' не является палиндромом.")