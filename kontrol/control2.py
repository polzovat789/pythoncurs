# Функция для запроса числа у пользователя и вывода его квадрата
def square_of_number():
    try:
        # Запрашиваем число у пользователя
        num = float(input("Введите число: "))
        # Выводим квадрат числа
        print(f"Квадрат числа {num} равен {num ** 2}")
    except ValueError:
        print("Ошибка: Введено не число. Пожалуйста, введите корректное число.")

# Функция для запроса числа у пользователя и определения, четное оно или нечетное
def even_or_odd():
    try:
        # Запрашиваем число у пользователя
        num = int(input("Введите целое число: "))
        # Проверяем, четное ли число
        if num % 2 == 0:
            print(f"Число {num} является четным.")
        else:
            print(f"Число {num} является нечетным.")
    except ValueError:
        print("Ошибка: Введено не целое число. Пожалуйста, введите корректное целое число.")

# Вызов функций
square_of_number()  # Вызов функции для квадрата числа
even_or_odd()       # Вызов функции для определения четности числа
