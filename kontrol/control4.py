def add_one(digits):
    # Начинаем с последней цифры
    for i in range(len(digits) - 1, -1, -1):
        # Если текущая цифра меньше 9, просто увеличиваем её на 1
        if digits[i] < 9:
            digits[i] += 1
            return digits
        # Если текущая цифра равна 9, ставим 0 и переходим к предыдущей цифре
        digits[i] = 0

    # Если все цифры были 9 (например, 999 + 1 = 1000), добавляем 1 в начало списка
    return [1] + digits


# Примеры использования:
print(add_one([9]))  # [1, 0]
print(add_one([1, 2, 3]))  # [1, 2, 4]
print(add_one([1, 1, 9]))  # [1, 2, 0]
print(add_one([9, 9, 9]))  # [1, 0, 0, 0]
